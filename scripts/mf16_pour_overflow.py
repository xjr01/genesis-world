        upm = (z_all > prev_pos[:, 2]) & (prev_pos[:, 2] < Z_RIM) & (z_all >= Z_RIM)
        uz = np.clip(
            (Z_RIM - prev_pos[:, 2]) / np.maximum(z_all - prev_pos[:, 2], 1e-12),
            0.0,
            1.0,
        )
