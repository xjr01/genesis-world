# A mug particle is not legally overflowed merely because it rises through the horizontal rim
# plane: the centre of a connected dome does exactly that.  Legal overflow is a two-stage path.
# First the particle path must reach a fixed annulus adjacent to the *inner* lip at rim height;
# then it must cross outward beyond the outer wall while still at rim height.  Requiring the
# z-plane crossing itself to occur in the annulus is too strict: a genuine central cap can rise
# first and only later spread radially to the lip.  The 2 ps inner band is geometric (one PBD
# support radius plus one particle radius), fixed before any run.
