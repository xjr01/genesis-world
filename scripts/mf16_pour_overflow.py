        # per accepted substep in the substep-interpolated jug-local frame, spout-aware.  In the
        # spout sector (azimuth 180 deg +/- 20 deg) the frame probes below disagree with the
        # solver BY DESIGN: the frame probe still uses the flat 0.320 clearance plane while the
        # solver uses the spout-aware top surface z_top(az) = 0.316 + spout_dz*w(az) + particle
        # radius (0.318 at the beak centre).  Such disagreement is EXPECTED and benign; the
        # frame probes are kept only as diagnostic counters.
        if args.jug_hist:
            solver_jug_staged, solver_jug_direct = solver.boundary_ball_jug_history()
        else:
            solver_jug_staged = np.zeros(n_fluid, dtype=bool)
            solver_jug_direct = np.zeros(n_fluid, dtype=bool)
        cur_jlocal = inverse_transform_points(safe, origin, quat)
        pr, cr = np.linalg.norm(prev_jlocal[:, :2], axis=1), np.linalg.norm(cur_jlocal[:, :2], axis=1)
        pzj, czj = prev_jlocal[:, 2], cur_jlocal[:, 2]
        jug_clear_z = Z_RIM + 0.5 * ps
        jug_wall_z_lo = -0.5 * ps
        jug_wall_z_hi = Z_RIM + 0.5 * ps
        up = (czj > pzj) & (pzj < jug_clear_z) & (czj >= jug_clear_z)
