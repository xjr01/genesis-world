            r_np = np.sqrt(safe_np[:, 0] ** 2 + safe_np[:, 1] ** 2)
            in_mug = (r_np <= R_IN + ps) & (safe_np[:, 2] >= Z_FLOOR - ps)
            z_s = float(np.percentile(safe_np[in_mug, 2], 99)) if in_mug.any() else float("nan")
