        safe_c = np.nan_to_num(c, nan=0.0, posinf=0.0, neginf=0.0)
        r_all = np.linalg.norm(safe[:, :2], axis=1)
        z_all = safe[:, 2]
        active_fluid = int(solver.particles_ng.active.to_numpy()[:n_fluid, 0].sum())
        max_active_fluid_error = max(max_active_fluid_error, abs(active_fluid - n_fluid))
