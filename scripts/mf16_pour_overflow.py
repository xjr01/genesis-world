def smoothstep(u):
    u = min(max(u, 0.0), 1.0)
    return u * u * (3.0 - 2.0 * u)


def _ramp(t, t0, t1):
    return smoothstep((t - t0) / max(t1 - t0, 1e-9))


def quat_roty_neg(theta):
    """Quaternion (w, x, y, z) of rotY(-theta): maps the mesh local +z to the jug axis."""
    return np.array([np.cos(theta / 2.0), 0.0, -np.sin(theta / 2.0), 0.0])


def jug_origin_p():
    return np.array([PIVOT_X + R_JUG, 0.0, PIVOT_Z - Z_RIM])


def jug_park():
    return np.array([PARK_X, 0.0, PZ])


def jug_theta(t):
    """Jug tilt: main pour -> fill -> stream stop/dome hold -> overfill -> upright.

    The return to upright shares the glide window [T_BACK, T_PARK1] with the park translation:
    coming upright while still at the pour stance puts the jug's outer wall through the mug rim.
    """
    th_max = np.deg2rad(TILT_MAX_DEG)
    th_tr = np.deg2rad(TILT_TRICKLE_DEG)
    th_hold = np.deg2rad(TILT_DOME_HOLD_DEG)
    if t < T_TILT0:
        return 0.0
    if t < T_TILT1:
        return th_max * _ramp(t, T_TILT0, T_TILT1)
    if t < T_TRICKLE:
        return th_max
    if t < T_DOME_STOP:
        # Reach the drain angle promptly, then hold it long enough for the jug to empty.
        # Stretching this ramp over the whole phase left a large, silent volume in the jug.
        return th_max + (th_tr - th_max) * _ramp(
            t, T_TRICKLE, min(T_TRICKLE + TRICKLE_RAMP, T_DOME_STOP)
        )
    if t < T_OVERFILL:
        # Explicitly retreat below the pouring angle and hold.  Dome evidence is only accepted
        # after the jug census has stabilized, so the incoming stream cannot create the apex.
        angle_start = T_DOME_STOP + 0.5 * STOP_RAMP
        return th_tr + (th_hold - th_tr) * _ramp(
            t, angle_start, min(T_DOME_STOP + STOP_RAMP, T_OVERFILL)
        )
    th_over = np.deg2rad(TILT_OVERFILL_DEG)
    if t < T_BACK:
        return th_hold + (th_over - th_hold) * _ramp(
            t, T_OVERFILL, min(T_OVERFILL + OVERFILL_RAMP, T_BACK)
        )
    return th_over * (1.0 - _ramp(t, T_BACK, T_PARK1))


def jug_pose(t):
    """One pure source of truth for jug translation, quaternion, axis, angle and tilt blend.

    Pure function of t. Phase B is a pure vertical lift to the pivot height, so the upright
    body clears the mug rim before the approach starts; phase C combines the approach, the
    descent and the tilt on one smoothstep, so the jug arrives at the pour stance already at
    tilt-max and no upright pose hangs over the mug. D onward rotates about the pour-side lip
    pivot PIVOT = (pivot_x, 0, pivot_z) - the pour-side lip point of the pour stance
    (origin_p + L*a0 - R_JUG*e1 with a0 = +z, e1 = +x) - which stays fixed in the world while
    the body tilts. The theta return and the park glide share [T_BACK, T_PARK1]: coming upright
    while still over the mug would sink the jug wall into the mug rim.
    """
    th = jug_theta(t)
    a = np.array([-np.sin(th), 0.0, np.cos(th)])  # bottom -> mouth
    e1 = np.array([np.cos(th), 0.0, np.sin(th)])  # in-plane, toward the pour side
    origin_0 = np.array([PX, 0.0, PZ])
    lift_top = np.array([PX, 0.0, PIVOT_Z - T_JUG_BOTTOM])
    origin_p = jug_origin_p()
    pivot = np.array([PIVOT_X, 0.0, PIVOT_Z])
    rot = (pivot - Z_RIM * a + R_JUG * e1) - origin_p  # vanishes at theta = 0
    u_lift = _ramp(t, T_LIFT0, T_LIFT1)
    u_tilt = _ramp(t, T_TILT0, T_TILT1)
    u_park = _ramp(t, T_BACK, T_PARK1)
    # Stop sequence: first lift/retreat the still-78-degree jug away from the mug, then reduce
    # its angle.  During the independent overfill pulse the offset is smoothly removed.  This
    # ordering is required by the actual ball-set clearance check; a fixed-pivot 65-degree pose
    # intersects the mug rim.
    stop_mid = T_DOME_STOP + 0.5 * STOP_RAMP
    if t < T_DOME_STOP:
        u_stop = 0.0
    elif t < stop_mid:
        u_stop = _ramp(t, T_DOME_STOP, stop_mid)
    elif t < T_OVERFILL:
        u_stop = 1.0
    elif t < T_OVERFILL + OVERFILL_RAMP:
        u_stop = 1.0 - _ramp(t, T_OVERFILL, T_OVERFILL + OVERFILL_RAMP)
    else:
        u_stop = 0.0
    origin = (origin_0
              + u_lift * (lift_top - origin_0)
              + u_tilt * (origin_p - lift_top)
              + rot
              + u_stop * np.array([STOP_RETREAT_X, 0.0, STOP_LIFT_Z])
              + u_park * (jug_park() - origin_p))
    quat = quat_roty_neg(th).astype(np.float32)
    return origin.astype(np.float32), quat, a.astype(np.float32), th, u_tilt


def transform_points(local, pos, quat):
    """Rigidly transform local rows using a normalized (w,x,y,z) quaternion."""
    q = np.asarray(quat, dtype=np.float64)
    q /= np.linalg.norm(q)
    w, x, y, z = q
    rot = np.array(
        [[1 - 2 * (y*y + z*z), 2 * (x*y - z*w), 2 * (x*z + y*w)],
         [2 * (x*y + z*w), 1 - 2 * (x*x + z*z), 2 * (y*z - x*w)],
         [2 * (x*z - y*w), 2 * (y*z + x*w), 1 - 2 * (x*x + y*y)]],
        dtype=np.float64,
    )
    return np.asarray(local, dtype=np.float64) @ rot.T + np.asarray(pos, dtype=np.float64)


def inverse_transform_points(world, pos, quat):
    """World rows to the local frame of ``(pos, quat)``."""
    q = np.asarray(quat, dtype=np.float64)
    q /= np.linalg.norm(q)
    w, x, y, z = q
    rot = np.array(
        [[1 - 2 * (y*y + z*z), 2 * (x*y - z*w), 2 * (x*z + y*w)],
         [2 * (x*y + z*w), 1 - 2 * (x*x + z*z), 2 * (y*z - x*w)],
         [2 * (x*z - y*w), 2 * (y*z + x*w), 1 - 2 * (x*x + y*y)]],
        dtype=np.float64,
    )
    return (np.asarray(world, dtype=np.float64) - np.asarray(pos, dtype=np.float64)) @ rot


def segment_outward_cylinder_crossing(prev, cur, radius):
    """Exact segment intersection with an infinite z-cylinder for inside->outside paths.

    Returns ``(crossed, u, z)`` arrays.  Radial linear interpolation is not exact because the
    radius is a norm; the positive quadratic root is the first outward intersection when the
    segment starts inside and ends outside.
    """
    p = np.asarray(prev, dtype=np.float64)
    q = np.asarray(cur, dtype=np.float64)
    dxy = q[:, :2] - p[:, :2]
    a = np.einsum("ij,ij->i", dxy, dxy)
    b = 2.0 * np.einsum("ij,ij->i", p[:, :2], dxy)
    c = np.einsum("ij,ij->i", p[:, :2], p[:, :2]) - radius * radius
    pr = np.linalg.norm(p[:, :2], axis=1)
    qr = np.linalg.norm(q[:, :2], axis=1)
    crossed = (pr < radius) & (qr >= radius) & (a > 1e-20)
    disc = np.maximum(b * b - 4.0 * a * c, 0.0)
    u = np.zeros(len(p), dtype=np.float64)
    u[crossed] = (-b[crossed] + np.sqrt(disc[crossed])) / (2.0 * a[crossed])
    crossed &= (u >= 0.0) & (u <= 1.0)
    z = p[:, 2] + np.clip(u, 0.0, 1.0) * (q[:, 2] - p[:, 2])
    return crossed, u, z


def segment_inward_cylinder_crossing(prev, cur, radius):
    """Exact outside->inside cylinder intersection, expressed in prev->cur parameterization."""
    crossed_rev, u_rev, z = segment_outward_cylinder_crossing(cur, prev, radius)
    return crossed_rev, 1.0 - u_rev, z


def segment_downward_plane_crossing(prev, cur, z_plane):
    """Exact segment crossing of a horizontal plane in the downward direction."""
    p = np.asarray(prev, dtype=np.float64)
    q = np.asarray(cur, dtype=np.float64)
    crossed = (p[:, 2] >= z_plane) & (q[:, 2] < z_plane)
    u = np.zeros(len(p), dtype=np.float64)
    dz = q[:, 2] - p[:, 2]
    good = crossed & (np.abs(dz) > 1e-20)
    u[good] = (z_plane - p[good, 2]) / dz[good]
    point = p + np.clip(u, 0.0, 1.0)[:, None] * (q - p)
    return crossed & good & (u >= 0.0) & (u <= 1.0), u, point


def load_ball_asset(path, body, kinematic):
    with np.load(path) as data:
        local = np.asarray(data["pos_local"], dtype=np.float32)
        meta = json.loads(str(data["meta"].item()))
    assert meta["body"] == body and bool(meta["kinematic"]) is kinematic
    assert local.ndim == 2 and local.shape[1] == 3 and np.isfinite(local).all()
    assert "mf16_balls.py shared dictionaries" in meta["geometry"]["source"]
    if body == "jug":
        assert float(meta["geometry"]["spout"]["center_deg"]) == 180.0
        assert float(meta["geometry"]["spout"]["spout_half_deg"]) == 20.0
        assert float(meta["geometry"]["spout"]["spout_dz"]) == -0.002
        assert float(meta["geometry"]["spout"]["spout_dr"]) == 0.030
        assert float(meta["geometry"]["side"]) == 1.0
    return local, meta


def assert_timeline_contract(mug_local, jug_local, t1):
    """Use the actual ball assets to prove hash containment and no vessel interpenetration."""
    mug_tree = cKDTree(np.asarray(mug_local, dtype=np.float64))
    min_dist, min_t = float("inf"), 0.0
    for t in np.linspace(0.0, t1, max(int(round(t1 / 0.05)) + 1, 2)):
        pos, quat, _, _, _ = jug_pose(float(t))
        world = transform_points(jug_local, pos, quat)
        lo, hi = world.min(axis=0), world.max(axis=0)
        assert np.all(lo >= LOWER_BOUND - 1e-7), (t, lo)
        assert np.all(hi < UPPER_BOUND), (t, hi)
        d = float(mug_tree.query(world, k=1, workers=-1)[0].min())
        if d < min_dist:
            min_dist, min_t = d, float(t)
    assert min_dist >= PS_FULL - 1e-6, (
        f"vessel ball sets interpenetrate: min centre distance {min_dist:.6f} at t={min_t:.3f}"
    )
    print(f"timeline asset contract: hash envelope PASS; min mug/jug ball distance "
          f"{min_dist:.6f} at t={min_t:.3f}s")


def coherent_mug_surface(pos, vel, bulk_mask, ps):
    """Return a broad, locally supported free-surface height and coherent dome count.

    A particle percentile is easily fooled by the incoming jet.  Here the surface is sampled
    once per 1.5-particle 2-D column over the mug core, only from slow particles that still
    belong to the mug bulk.  Each column top must have a genuine 3-D local neighbourhood, and
    the reported height is the 75th percentile across columns.  A narrow jet or a few droplets
    can therefore occupy some columns, but cannot masquerade as a cup-wide convex surface.
    """
    core_r = R_IN - 2.0 * ps
    speed = np.linalg.norm(vel, axis=1)
    r = np.linalg.norm(pos[:, :2], axis=1)
    eligible = bulk_mask & (r <= core_r) & (speed <= 0.2)
    idx = np.flatnonzero(eligible)
    if idx.size < 32:
        return float("nan"), 0

    cell = 1.5 * ps
    nxy = int(np.ceil(2.0 * core_r / cell)) + 1
    ij = np.floor((pos[idx, :2] + core_r) / cell).astype(np.int32)
    keys = ij[:, 0].astype(np.int64) * nxy + ij[:, 1]
    order = np.lexsort((pos[idx, 2], keys))
    sorted_idx, sorted_keys = idx[order], keys[order]
    starts = np.r_[0, 1 + np.flatnonzero(sorted_keys[1:] != sorted_keys[:-1])]
    ends = np.r_[starts[1:], sorted_idx.size]
    # Require several slow particles in a vertical column, then take its highest one.  The
    # subsequent spherical-neighbour test rejects an isolated top particle.
    tops = np.asarray([sorted_idx[e - 1] for s, e in zip(starts, ends) if e - s >= 4], dtype=np.int64)
    if tops.size < 24:
        return float("nan"), 0
    bulk_idx = np.flatnonzero(bulk_mask)
    tree = cKDTree(np.asarray(pos[bulk_idx], dtype=np.float64))
    n_local = tree.query_ball_point(
        np.asarray(pos[tops], dtype=np.float64), r=1.75 * ps, return_length=True, workers=-1
    )
    tops = tops[np.asarray(n_local) >= 6]
    if tops.size < 24:
        return float("nan"), 0
    top_z = pos[tops, 2]
    z_surface = float(np.percentile(top_z, 75.0))
    n_dome = int(np.count_nonzero(top_z >= Z_RIM + 0.5 * ps))
    return z_surface, n_dome


def phase_of(t):
    if t < T_LIFT0:
        return 0  # A rest
    if t < T_TILT0:
        return 1  # B lift
    if t < T_TILT1:
        return 2  # C tilt up
    if t < T_TRICKLE:
        return 3  # D pour at tilt-max
    if t < T_BACK:
        return 4  # E trickle + dome
    return 5 if t < T_PARK1 else 6  # F overflow + return/glide, G settle


def longest_true_run(mask):
    """Length (frames) of the longest run of True in a 1-D bool array."""
    best = cur = 0
    for v in mask:
        cur = cur + 1 if v else 0
        best = max(best, cur)
    return best


def best_window_frac(t_arr, ok, win_dur):
    """Max over start frames of the fraction of `ok` inside the ~`win_dur` window from it."""
    n = len(t_arr)
    if n == 0:
        return 0.0, 0, 0
    best_frac, bi, bj = 0.0, 0, 0
    j = 0
    csum = np.concatenate([[0], np.cumsum(ok.astype(np.int64))])
    for i in range(n):
        while j + 1 < n and t_arr[j + 1] - t_arr[i] <= win_dur + 0.5 * DT:
            j += 1
        if t_arr[j] - t_arr[i] >= win_dur:
            frac = (csum[j + 1] - csum[i]) / (j + 1 - i)
            if frac > best_frac:
                best_frac, bi, bj = frac, i, j
    return best_frac, bi, bj


