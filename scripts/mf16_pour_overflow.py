        jug_inbound_tunnel_now = frame_jug_inbound_tunnel_probe & ~jug_staged_top_reentry
        jug_bottom_cross, _, jug_bottom_point = segment_downward_plane_crossing(
            prev_jlocal, cur_jlocal, -0.5 * ps
        )
        jug_bottom_cross_r = np.linalg.norm(jug_bottom_point[:, :2], axis=1)
        jug_bottom_tunnel_now = (
            jug_open & jug_bottom_entered
            & (
                (jug_bottom_cross & (jug_bottom_cross_r <= R_JUG + T_JUG_WALL + ps))
                | (~jug_bottom_cross & (czj < -0.5 * ps)
                   & (cr <= R_JUG + T_JUG_WALL + ps))
            )
        )
