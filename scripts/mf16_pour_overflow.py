        n_frame_jug_wall_direct = int(
            (frame_jug_wall_tunnel_probe & solver_jug_direct)[n_coffee:].sum()
        )
        n_jug_cleared = int(jug_cleared[n_coffee:].sum())
        n_jug_wall_tunnel = int(jug_wall_tunnel[n_coffee:].sum())
        n_jug_bottom_tunnel = int(jug_bottom_tunnel[n_coffee:].sum())
        n_mug_rim_crossed = int(mug_rim_crossed.sum())
        n_mug_cleared = int(mug_cleared.sum())
        n_mug_wall_tunnel = int(mug_wall_tunnel.sum())
        n_mug_bottom_tunnel = int(mug_bottom_tunnel.sum())
        n_leak = n_jug_wall_tunnel + n_jug_bottom_tunnel + n_mug_wall_tunnel + n_mug_bottom_tunnel
        sum_c = float(safe_c[valid].sum())
        std_c = float(safe_c[valid].std())
        ke = float(0.5 * np.nansum((safe_v[valid] ** 2).sum(axis=1)))
        rel_j = safe[n_coffee:n_fluid] - origin
        s_j = rel_j @ axis
        r_j = np.linalg.norm(rel_j - s_j[:, None] * axis[None, :], axis=1)
