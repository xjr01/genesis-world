        # A particle centre that crosses the outer wall radius at/above .320, or is already
        # outside there at the previous accepted frame endpoint, is in open space above the
        # strict clearance plane.  Record that high exit before evaluating low-wall occupancy;
        # this is not a relaxed threshold and cannot legalize a crossing below .320.
        jug_high_clear_now = jug_open & (
            legal_jug_cross
            | (jug_outer_cross & (jug_outer_z >= jug_clear_z))
            | ((pr >= jug_outer_r) & (pzj >= jug_clear_z))
        )
        # Frame-level wall-crossing probe, kept for diagnostics.  Under --jug-hist the solver's
        # spout-aware substep history is authoritative: an unstaged frame chord or the solver's
        # irreversible direct counter is a wall tunnel.  Staging only excuses the rounded frame
        # chord at the physical top face; it never grants a permanent exemption to a later
        # low-z outside->inside wall penetration, and staged must never wash a set direct.
        frame_jug_wall_tunnel_probe = (
            jug_open & ~jug_high_clear_now & jug_wall_entered
            & (
                (jug_outer_cross & (jug_outer_z >= jug_wall_z_lo) & (jug_outer_z < jug_clear_z))
                | (~jug_outer_cross & (cr >= jug_outer_r)
                   & (czj >= jug_wall_z_lo) & (czj < jug_clear_z))
            )
        )
