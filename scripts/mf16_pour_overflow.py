            frame_dumps[f"jug_wall_entered_{dump_frames[i]:g}"] = jug_wall_entered[:n_fluid].copy()
            frame_dumps[f"jug_bottom_entered_{dump_frames[i]:g}"] = jug_bottom_entered[:n_fluid].copy()
            frame_dumps[f"mug_wall_entered_{dump_frames[i]:g}"] = mug_wall_entered[:n_fluid].copy()
            frame_dumps[f"mug_bottom_entered_{dump_frames[i]:g}"] = mug_bottom_entered[:n_fluid].copy()
