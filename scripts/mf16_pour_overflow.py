        not_jug = np.ones(n_fluid, dtype=bool)
        not_jug[n_coffee:] = ~in_jug_fp
        in_mug = (r_all <= R_IN + ps) & (z_all >= Z_FLOOR - ps) & valid
        bulk_surface = in_mug & not_jug & mug_resident & ~mug_cleared
        z_surf, n_dome = coherent_mug_surface(safe, safe_v, bulk_surface, ps)
        n_coffee_mug = int(in_mug[:n_coffee].sum())
        legal_mug_out = mug_cleared & ~mug_wall_tunnel & ~mug_bottom_tunnel & not_jug & valid
        n_over_rim = int((legal_mug_out & (z_all > Z_RIM + 0.5 * ps)
                          & (r_all > R_OUT - ps)).sum())
        outer_wall_mask = (
            legal_mug_out & (r_all >= R_OUT - 0.5 * ps) & (r_all <= R_OUT + 2.5 * ps)
            & (z_all >= 0.02) & (z_all <= Z_RIM)
        )
        n_outer_wall = int(outer_wall_mask.sum())
        outer_wall_run = np.where(outer_wall_mask, outer_wall_run + 1, 0)
        outer_wall_max_run = np.maximum(outer_wall_max_run, outer_wall_run)
        wall_speeds = np.linalg.norm(safe_v[outer_wall_mask], axis=1)
        wall_runs_s = outer_wall_run[outer_wall_mask].astype(np.float64) * DT
        wall_speed_p50 = float(np.median(wall_speeds)) if len(wall_speeds) else 0.0
        wall_speed_p90 = float(np.percentile(wall_speeds, 90)) if len(wall_speeds) else 0.0
        wall_res_p50 = float(np.median(wall_runs_s)) if len(wall_runs_s) else 0.0
        wall_res_p90 = float(np.percentile(wall_runs_s, 90)) if len(wall_runs_s) else 0.0
        wall_res_max = float(outer_wall_max_run.max() * DT)
        n_wall_ever_1s = int(np.count_nonzero(outer_wall_max_run >= round(1.0 / DT)))
        n_wall_persistent_1s = int(np.count_nonzero(outer_wall_run >= round(1.0 / DT)))
        wall_lifetime_runs = outer_wall_max_run[outer_wall_max_run > 0].astype(np.float64) * DT
        wall_max_res_p90 = float(np.percentile(wall_lifetime_runs, 90)) if len(wall_lifetime_runs) else 0.0
        n_outer_wall_coffee = int(outer_wall_mask[:n_coffee].sum())
        n_outer_wall_milk = int(outer_wall_mask[n_coffee:].sum())
        n_table = int((legal_mug_out & (z_all <= 2.5 * ps)
                       & (r_all > R_OUT + 3.0 * ps)).sum())
        n_milk_jug = int(((s_j > Z_FLOOR - ps) & (s_j < Z_RIM + ps) & (r_j <= R_JUG + ps)).sum())
        n_milk_mug = int(in_mug[n_coffee:].sum())
        if i in dump_frames:
            # Full fluid state plus the exact history masks required by the independent surface
            # audit.  These are diagnostics only; no state is written back to the solver.
            frame_dumps[f"{dump_frames[i]:g}"] = safe[:n_fluid].copy()
            frame_dumps[f"vel_{dump_frames[i]:g}"] = safe_v[:n_fluid].copy()
            frame_dumps[f"c_{dump_frames[i]:g}"] = solver.particles.c.to_numpy()[:n_fluid, 0].copy()
            frame_dumps[f"pose_{dump_frames[i]:g}"] = np.concatenate([origin, quat])
            frame_dumps[f"valid_{dump_frames[i]:g}"] = valid[:n_fluid].copy()
            frame_dumps[f"mug_resident_{dump_frames[i]:g}"] = mug_resident[:n_fluid].copy()
