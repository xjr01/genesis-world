    mug_bottom_entered = mug_resident & (prev_pos[:, 2] < Z_FLOOR + 0.5 * ps)
    mug_wall_tunnel = np.zeros(n_fluid, dtype=bool)
    mug_bottom_tunnel = np.zeros(n_fluid, dtype=bool)
    outer_wall_run = np.zeros(n_fluid, dtype=np.int32)
    outer_wall_max_run = np.zeros(n_fluid, dtype=np.int32)
